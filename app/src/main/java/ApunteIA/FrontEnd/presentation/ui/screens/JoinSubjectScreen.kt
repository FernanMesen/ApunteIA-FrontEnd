@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun JoinSubjectScreen(
    onBack: () -> Unit,
    onJoinSuccess: () -> Unit = {},
    viewModel: JoinSubjectViewModel = hiltViewModel()
) {
    var courseCode by remember { mutableStateOf("") }
    var showCreateDialog by remember { mutableStateOf(false) }
    var createName by remember { mutableStateOf("") }
    var createCode by remember { mutableStateOf("") }
    var createDescription by remember { mutableStateOf("") }
    val uiState by viewModel.uiState.collectAsState()
    val filteredCourses = remember(uiState.availableCourses, uiState.searchQuery) {
        val query = uiState.searchQuery.trim().lowercase()
        if (query.isEmpty()) uiState.availableCourses
        else uiState.availableCourses.filter {
            it.name.lowercase().contains(query) ||
                it.code.lowercase().contains(query) ||
                it.description.lowercase().contains(query)
        }
    }

    LaunchedEffect(uiState.createError) {
        // Keep the dialog open and preserve fields while createError is displayed.
    }

    if (showCreateDialog) {
        AlertDialog(
            onDismissRequest = { if (!uiState.isCreating) showCreateDialog = false },
            title = { Text(stringResource(R.string.create_course), fontWeight = FontWeight.Bold) },
            text = {
                Column(
                    modifier = Modifier.verticalScroll(rememberScrollState()),
                    verticalArrangement = Arrangement.spacedBy(12.dp)
                ) {
                    OutlinedTextField(
                        value = createName,
                        onValueChange = { createName = it },
                        label = { Text(stringResource(R.string.course_name)) },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth()
                    )
                    OutlinedTextField(
                        value = createCode,
                        onValueChange = { createCode = it },
                        label = { Text(stringResource(R.string.course_code_optional)) },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth()
                    )
                    OutlinedTextField(
                        value = createDescription,
                        onValueChange = { createDescription = it },
                        label = { Text(stringResource(R.string.course_description)) },
                        modifier = Modifier.fillMaxWidth()
                    )
                    Text(
                        text = stringResource(R.string.course_code_autogenerated_help),
                        fontSize = 12.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    uiState.createError?.let {
                        Text(text = it, color = MaterialTheme.colorScheme.error, fontSize = 13.sp)
                    }
                }
            },
            confirmButton = {
                Button(
                    enabled = !uiState.isCreating,
                    onClick = {
                        viewModel.createCourse(createName, createCode, createDescription) {
                            showCreateDialog = false
                            createName = ""
                            createCode = ""
                            createDescription = ""
                            onJoinSuccess()
                        }
                    }
                ) {
                    if (uiState.isCreating) {
                        CircularProgressIndicator(modifier = Modifier.size(18.dp), strokeWidth = 2.dp)
                    } else Text(stringResource(R.string.create_course))
                }
            },
            dismissButton = {
                OutlinedButton(onClick = { showCreateDialog = false }) {
                    Text(stringResource(R.string.cancel))
                }
            }
        )
    }

    Scaffold(
        containerColor = MaterialTheme.colorScheme.background,
        topBar = {
            JoinSubjectTopBar(onBack = onBack)
        }
    ) { paddingValues ->
        PullToRefreshBox(
            isRefreshing = uiState.isLoading,
            onRefresh = { viewModel.refreshAvailableCourses() },
            modifier = Modifier
                .fillMaxSize()
                .padding(paddingValues)
        ) {
            ResponsiveContent(maxWidth = 840.dp) {
                LazyColumn(
                    modifier = Modifier
                        .fillMaxSize()
                        .imePadding()
                        .padding(horizontal = 24.dp),
                    verticalArrangement = Arrangement.spacedBy(24.dp)
                ) {
                item {
                    CodeJoinCard(
                        value = courseCode,
                        onValueChange = { courseCode = it },
                        isJoining = uiState.isJoiningByCode,
                        onJoin = {
                            viewModel.joinByCode(courseCode, onJoinSuccess)
                        }
                    )
                }

                item {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(12.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        OutlinedTextField(
                            value = uiState.searchQuery,
                            onValueChange = viewModel::onSearchQueryChange,
                            label = { Text(stringResource(R.string.search_courses)) },
                            singleLine = true,
                            modifier = Modifier.weight(1f)
                        )
                        FilledTonalButton(
                            onClick = { showCreateDialog = true },
                            modifier = Modifier.height(56.dp)
                        ) {
                            Text(stringResource(R.string.create_course))
                        }
                    }
                }

                if (uiState.error != null) {
                    item {
                        Card(
                            modifier = Modifier.fillMaxWidth(),
                            colors = CardDefaults.cardColors(
                                containerColor = MaterialTheme.colorScheme.errorContainer
                            ),
                            shape = RoundedCornerShape(16.dp)
                        ) {
                            Column(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(16.dp),
                                horizontalAlignment = Alignment.CenterHorizontally
                            ) {
                                Text(
                                    text = uiState.error.orEmpty(),
                                    color = MaterialTheme.colorScheme.onErrorContainer,
                                    fontSize = 14.sp
                                )
                                Spacer(modifier = Modifier.height(8.dp))
                                Button(
                                    onClick = { viewModel.refreshAvailableCourses() },
                                    colors = ButtonDefaults.buttonColors(
                                        containerColor = MaterialTheme.colorScheme.error
                                    )
                                ) {
                                    Text(stringResource(R.string.retry))
                                }
                            }
                        }
                    }
                }

                item {
                    Text(
                        text = stringResource(R.string.available_courses_header),
                        fontSize = 13.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(start = 4.dp)
                    )
                }

                if (uiState.isLoading && uiState.availableCourses.isEmpty()) {
                    item {
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 32.dp),
                            contentAlignment = Alignment.Center
                        ) {
                            CircularProgressIndicator()
                        }
                    }
                } else if (uiState.searchQuery.isNotBlank() && filteredCourses.isEmpty()) {
                    item {
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(vertical = 32.dp),
                            contentAlignment = Alignment.Center
                        ) {
                            Column(horizontalAlignment = Alignment.CenterHorizontally) {
                                Text(
                                    stringResource(R.string.no_search_results),
                                    fontSize = 14.sp,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                    textAlign = TextAlign.Center
                                )
                                TextButton(onClick = { viewModel.onSearchQueryChange("") }) {
                                    Text(stringResource(R.string.clear_search))
                                }
                            }
                        }
                    }
                } else if (filteredCourses.isEmpty()) {
                    item {
                        Column(
                            modifier = Modifier.fillMaxWidth().padding(vertical = 32.dp),
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            Text(
                                stringResource(
                                    if (uiState.totalCatalogCount == 0)
                                        R.string.no_courses_available
                                    else R.string.already_in_all_courses
                                ),
                                fontSize = 14.sp,
                                color = MaterialTheme.colorScheme.onSurfaceVariant,
                                textAlign = TextAlign.Center
                            )
                            Spacer(modifier = Modifier.height(12.dp))
                            FilledTonalButton(onClick = { showCreateDialog = true }) {
                                Text(stringResource(R.string.create_course))
                            }
                        }
                    }
                } else {
                    items(filteredCourses) { course ->
                        AvailableCourseCard(
                            course = course,
                            isJoining = uiState.joiningCourseId == course.courseId,
                            onJoin = {
                                viewModel.joinCourse(course, onJoinSuccess)
                            }
                        )
                    }
                }

                item {
                    Text(
                        text = stringResource(R.string.courses_info_notice),
                        fontSize = 13.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        textAlign = TextAlign.Center,
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(horizontal = 20.dp, vertical = 8.dp),
                        lineHeight = 18.sp
                    )
                    Spacer(modifier = Modifier.height(32.dp))
                }
            }
        }
    }
}
}

@Composable
fun JoinSubjectTopBar(onBack: () -> Unit) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .statusBarsPadding()
            .padding(horizontal = 16.dp, vertical = 16.dp),
        verticalAlignment = Alignment.CenterVertically
    ) {
        Box(
            modifier = Modifier
                .size(36.dp)
                .clip(CircleShape)
                .background(MaterialTheme.colorScheme.onSurface.copy(alpha = 0.1f))
                .clickable { onBack() },
            contentAlignment = Alignment.Center
        ) {
            Icon(
                imageVector = Icons.Default.KeyboardArrowLeft,
                contentDescription = stringResource(R.string.back),
                tint = MaterialTheme.colorScheme.onBackground,
                modifier = Modifier.size(20.dp)
            )
        }

        Spacer(modifier = Modifier.width(16.dp))

        Column {
            Text(
                text = stringResource(R.string.join_course_title),
                fontSize = 22.sp,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onBackground
            )
            Text(
                text = stringResource(R.string.join_course_subtitle),
                fontSize = 13.sp,
                color = MaterialTheme.colorScheme.onSurfaceVariant
            )
        }
    }
}

@Composable
fun CodeJoinCard(
    value: String,
    onValueChange: (String) -> Unit,
    isJoining: Boolean = false,
    onJoin: () -> Unit
) {
    val isDark = MaterialTheme.colorScheme.primary == SpaceCadet

    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(20.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant),
        elevation = CardDefaults.cardElevation(defaultElevation = 0.dp)
    ) {
        Row(
            modifier = Modifier
                .padding(16.dp)
                .fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            OutlinedTextField(
                value = value,
                onValueChange = onValueChange,
                placeholder = { Text(stringResource(R.string.course_code_placeholder), fontSize = 14.sp) },
                modifier = Modifier
                    .weight(1f)
                    .height(52.dp),
                shape = RoundedCornerShape(12.dp),
                colors = OutlinedTextFieldDefaults.colors(
                    focusedContainerColor = if (isDark) Color(0xFF1E2532) else Color.White,
                    unfocusedContainerColor = if (isDark) Color(0xFF1E2532) else Color.White,
                    focusedBorderColor = if (isDark) Color(0xFF394867) else Color(0xFFE2E2E2),
                    unfocusedBorderColor = if (isDark) Color(0xFF394867) else Color(0xFFE2E2E2),
                    focusedTextColor = MaterialTheme.colorScheme.onSurface,
                    unfocusedTextColor = MaterialTheme.colorScheme.onSurface
                ),
                singleLine = true
            )

            Spacer(modifier = Modifier.width(12.dp))

            Button(
                onClick = onJoin,
                enabled = !isJoining && value.isNotBlank(),
                modifier = Modifier.height(52.dp),
                shape = RoundedCornerShape(12.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = if (isDark) Color(0xFF5D7B92) else MaterialTheme.colorScheme.primary
                )
            ) {
                if (isJoining) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(18.dp),
                        color = Color.White,
                        strokeWidth = 2.dp
                    )
                } else {
                    Text(stringResource(R.string.join_course_button), fontWeight = FontWeight.Bold)
                }
            }
        }
    }
}

@Composable
fun AvailableCourseCard(
    course: AvailableCourse,
    isJoining: Boolean = false,
    onJoin: () -> Unit
) {
    val isDark = MaterialTheme.colorScheme.primary == SpaceCadet

    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(24.dp),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant),
        elevation = CardDefaults.cardElevation(defaultElevation = 0.dp)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Box(
                    modifier = Modifier
                        .size(48.dp)
                        .clip(RoundedCornerShape(12.dp))
                        .background(Color(android.graphics.Color.parseColor(course.colorHex))),
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = course.name.firstOrNull()?.toString() ?: "?",
                        color = Color.White,
                        fontSize = 20.sp,
                        fontWeight = FontWeight.Bold
                    )
                }

                Spacer(modifier = Modifier.width(16.dp))

                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = course.name,
                        fontSize = 17.sp,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                    if (course.description.isNotBlank()) {
                        Text(
                            text = course.description,
                            fontSize = 13.sp,
                            maxLines = 2,
                            overflow = androidx.compose.ui.text.style.TextOverflow.Ellipsis,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                    Text(
                        text = if (course.createdByName.isBlank())
                            stringResource(R.string.course_creator_unavailable)
                        else stringResource(R.string.course_created_by, course.createdByName),
                        fontSize = 12.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Text(
                        text = pluralStringResource(
                            R.plurals.course_student_count,
                            course.studentCount,
                            course.studentCount
                        ),
                        fontSize = 12.sp,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }

                Text(
                    text = course.id,
                    fontSize = 12.sp,
                    fontWeight = FontWeight.Medium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }

            Spacer(modifier = Modifier.height(16.dp))

            Button(
                onClick = onJoin,
                enabled = !isJoining,
                modifier = Modifier
                    .fillMaxWidth()
                    .height(48.dp),
                shape = RoundedCornerShape(12.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = if (isDark) Color(0xFF5D7B92) else MaterialTheme.colorScheme.primary,
                    contentColor = Color.White
                )
            ) {
                if (isJoining) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(18.dp),
                        color = Color.White,
                        strokeWidth = 2.dp
                    )
                } else {
                    Text(stringResource(R.string.join_course_action), fontWeight = FontWeight.Bold)
                }
            }
        }
    }
}

data class AvailableCourse(
    val name: String,
    val professor: String = "",
    val term: String = "",
    val id: String,
    val colorHex: String,
    val courseId: Long = 0L,
    val code: String = id,
    val description: String = "",
    val createdByName: String = "",
    val studentCount: Int = 0
)
